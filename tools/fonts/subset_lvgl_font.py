#!/usr/bin/env python3
"""Keeps only the LVGL symbols of tools/fonts/symbols.txt in one of LVGL's built-in fonts.

usage: subset_lvgl_font.py lv_font_montserrat_NN.c lv_symbol_def.h symbols.txt OUT.c

The input is LVGL's own file (lv_font_conv output, 4 bpp, uncompressed). The glyph bitmaps
and metrics are copied byte for byte, so a kept symbol draws exactly as before; letters and
kerning are dropped (the text is drawn by the embedded Noto Sans, src/app/fonts.cpp).
The output defines the same lv_font_montserrat_NN, so no caller changes. Standard library only.
"""
import re
import sys

font_path, def_path, list_path, out_path = sys.argv[1:5]
src = open(font_path).read()
name = re.search(r'lv_font_t (lv_font_montserrat_\d+) = \{', src).group(1)

names = [l.strip() for l in open(list_path) if l.strip() and not l.startswith('#')]
defs = dict(re.findall(r'#define LV_SYMBOL_(\w+)\s+"[^"]*"\s*/\*\s*\d+,\s*0x([0-9A-Fa-f]+)\s*\*/', open(def_path).read()))
unknown = [n for n in names if n not in defs]
if unknown:
    sys.exit(f'not LVGL symbols: {unknown}')
keep = sorted({int(defs[n], 16): n for n in names}.items())

# glyph_bitmap: each glyph's bytes follow a /* U+XXXX "..." */ comment.
bitmap_src = re.search(r'glyph_bitmap\[\] = \{(.*?)\n\};', src, re.S).group(1)
glyph_bytes = {}
for m in re.finditer(r'/\* U\+([0-9A-F]+) [^*]*\*/(.*?)(?=/\* U\+|\Z)', bitmap_src, re.S):
    glyph_bytes[int(m.group(1), 16)] = re.findall(r'0x[0-9a-fA-F]{2}', m.group(2))

dsc_src = re.search(r'glyph_dsc\[\] = \{(.*?)\n\};', src, re.S).group(1)
dscs = re.findall(r'\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), '
                  r'\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}', dsc_src)

# The code point of each glyph id, from the cmaps (ranges and sparse lists).
cps = [None]
for m in re.finditer(r'\.range_start = (\d+), \.range_length = (\d+), \.glyph_id_start = \d+,\s*'
                     r'\.unicode_list = (\w+), \.glyph_id_ofs_list = NULL', src):
    start, length, ulist = int(m.group(1)), int(m.group(2)), m.group(3)
    if ulist == 'NULL':
        cps += [start + i for i in range(length)]
    else:
        body = re.search(ulist + r'\[\] = \{(.*?)\};', src, re.S).group(1)
        cps += [start + int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body)]
if len(cps) != len(dscs):
    sys.exit(f'{font_path}: {len(dscs)} glyphs but {len(cps)} code points, not the expected format')
by_cp = dict(zip(cps, dscs))
missing = [n for cp, n in keep if cp not in by_cp or cp not in glyph_bytes]
if missing:
    sys.exit(f'{font_path} has no glyph for {missing}')

bitmap = []
glyphs = ['    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */']
for cp, n in keep:
    _, adv, bw, bh, ox, oy = by_cp[cp]
    glyphs.append(f'    {{.bitmap_index = {len(bitmap)}, .adv_w = {adv}, .box_w = {bw}, .box_h = {bh}, '
                  f'.ofs_x = {ox}, .ofs_y = {oy}}} /* LV_SYMBOL_{n} U+{cp:04X} */')
    bitmap += glyph_bytes[cp]

font = re.search(r'lv_font_t lv_font_montserrat_\d+ = \{(.*?)\n\};', src, re.S).group(1)
field = lambda f: re.search(r'\.' + f + r' = (-?\d+)', font).group(1)
static_bitmap = re.search(r'\.static_bitmap = (\d+)', font)
first = keep[0][0]
nl = '\n'
rows = [', '.join(bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]

out = f'''// Generated by tools/fonts/build_fonts.sh (subset_lvgl_font.py) from LVGL's {font_path.split("/")[-1]}:
// the symbols of tools/fonts/symbols.txt only, glyphs byte for byte. Do not edit.
// Source: LVGL v9.6.0 (MIT, LICENSE-LVGL.txt); symbol glyphs from Font Awesome 5 Free as bundled by
// LVGL (SIL Open Font License 1.1, Copyright (c) 2022 Fonticons, Inc., OFL-FontAwesome.txt).
// symbols: {" ".join(n for _, n in keep)}
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
    {("," + nl + "    ").join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{("," + nl).join(glyphs)}
}};

static const uint16_t unicode_list[] = {{{", ".join(hex(cp - first) for cp, _ in keep)}}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {first}, .range_length = {keep[-1][0] - first + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(keep)},
     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {field("line_height")},
    .base_line = {field("base_line")},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = {field("underline_position")},
    .underline_thickness = {field("underline_thickness")},
{"    .static_bitmap = " + static_bitmap.group(1) + "," + nl if static_bitmap else ""}    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
'''
open(out_path, 'w').write(out)
print(f'  {out_path.split("/")[-1]}: {len(keep)} symbols, {len(bitmap)} bitmap bytes')
